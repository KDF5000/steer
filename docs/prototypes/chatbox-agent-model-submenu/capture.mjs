import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.STEER_PLAYWRIGHT_MODULE||'playwright');
const browser=await chromium.launch({headless:true,...(process.env.STEER_CHROME_PATH?{executablePath:process.env.STEER_CHROME_PATH}:{})});
const output=fileURLToPath(new URL('./previews/',import.meta.url));
const origin=process.env.STEER_PROTOTYPE_ORIGIN||'http://127.0.0.1:3107';
const url=`${origin}/docs/prototypes/chatbox-agent-model-submenu/`;
const errors=[];
const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1.5});
page.on('pageerror',e=>errors.push(e.message));
await page.goto(url);await page.evaluate(()=>document.fonts.ready);
await page.screenshot({path:output+'01-default.png'});
await page.click('#agent-trigger');
await page.screenshot({path:output+'02-agent-menu.png'});
await page.hover('[data-row=frontend]');
assert.equal(await page.evaluate(()=>prototypeState.agent.id),'frontend');
assert.equal(await page.evaluate(()=>prototypeState.override),null);
await page.screenshot({path:output+'03-model-submenu.png'});
await page.screenshot({path:output+'03-model-submenu-detail.png',clip:{x:425,y:475,width:720,height:520}});
await page.click('[data-model="GPT-5.5"]');
assert.match(await page.locator('#agent-trigger').innerText(),/前端工程师[\s\S]*GPT-5.5/);
await page.screenshot({path:output+'04-model-changed.png'});
await page.locator('.ws-chatbox-wrap').screenshot({path:output+'04-model-changed-detail.png'});
await page.click('#agent-trigger');await page.hover('[data-row=reviewer]');
assert.equal(await page.evaluate(()=>prototypeState.agent.id),'frontend');
await page.locator('#model-picker input').fill('Gemini');
assert.equal(await page.locator('#model-options [role=menuitem]').count(),1);
await page.click('[data-model="Gemini-3.1-Pro-Preview"]');
assert.match(await page.locator('#agent-trigger').innerText(),/代码审查员[\s\S]*Gemini/);
await page.click('#agent-trigger');await page.hover('[data-row=reviewer]');
await page.click('[data-model=default]');
assert.match(await page.locator('#agent-trigger').innerText(),/GPT-5.5/);
await page.click('#agent-trigger');await page.click('[data-agent=frontend]');
assert.match(await page.locator('#agent-trigger').innerText(),/前端工程师[\s\S]*GPT-5.4/);
await page.click('#agent-trigger');await page.locator('[data-submenu=frontend]').focus();await page.keyboard.press('ArrowRight');
assert.equal(await page.locator('#model-picker').isVisible(),true);
await page.keyboard.press('Escape');assert.equal(await page.locator('#model-picker').isVisible(),false);
await page.keyboard.press('Escape');assert.equal(await page.locator('#agent-picker').isVisible(),false);
await page.click('.ws-chat-send');
assert.match(await page.locator('.ws-chat-message.agent').last().innerText(),/前端工程师[\s\S]*GPT-5.4/);
assert.equal(await page.evaluate(()=>prototypeState.agent.model),'GPT-5.4');
const mobile=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:2,isMobile:true,hasTouch:true});
mobile.on('pageerror',e=>errors.push(e.message));
await mobile.goto(url);await mobile.evaluate(()=>document.fonts.ready);
await mobile.screenshot({path:output+'05-mobile-default.png'});
await mobile.click('#agent-trigger');await mobile.screenshot({path:output+'06-mobile-agents.png'});
await mobile.click('[data-submenu=frontend]');await mobile.screenshot({path:output+'07-mobile-models.png'});
assert.equal(await mobile.locator('#agent-picker').isVisible(),false);
await mobile.click('.submenu-back');assert.equal(await mobile.locator('#agent-picker').isVisible(),true);
await mobile.click('[data-submenu=reviewer]');await mobile.click('[data-model="Gemini-3.1-Pro-Preview"]');
assert.match(await mobile.locator('#agent-trigger').innerText(),/代码审查员[\s\S]*Gemini/);
assert.ok(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
await mobile.screenshot({path:output+'08-mobile-changed.png'});
assert.deepEqual(errors,[]);await browser.close();
console.log('Verified cascading menu, preview without selection, agent/model selection, defaults, search, keyboard navigation, mobile back navigation, and simulated send.');
